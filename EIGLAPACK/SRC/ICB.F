      SUBROUTINE DSBGVX_C(N,KA,KB,AB,LDAB,BB,LDBB,Q,LDQ,IL,IU,M,W,Z,LDZ,
     &WORK,IWORK,IFAIL,INFO)
     &BIND(C,NAME="dsbgvx_c")
      USE :: ISO_C_BINDING
C
      IMPLICIT NONE
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: N
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: KA
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: KB
      REAL(KIND=C_DOUBLE),INTENT(INOUT) :: AB
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: LDAB
      REAL(KIND=C_DOUBLE),INTENT(INOUT) :: BB
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: LDBB
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: Q
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: LDQ
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: IL
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: IU
      DOUBLE PRECISION :: ABSTOL
      INTEGER(KIND=C_INT32_T),INTENT(OUT) :: M
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: W
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: Z
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: LDZ
      REAL(KIND=C_DOUBLE) :: WORK
      INTEGER(KIND=C_INT32_T) :: IWORK
      INTEGER(KIND=C_INT32_T),INTENT(OUT) :: IFAIL
      INTEGER(KIND=C_INT32_T),INTENT(OUT) :: INFO
      DOUBLE PRECISION :: DLAMCH
C
      DIMENSION AB(LDAB,N),BB(LDBB,N),Q(LDQ,N),W(N),Z(LDZ,N),WORK(7*N),
     &IWORK(5*N),IFAIL(*)
C
      ABSTOL = 2.D0*DLAMCH('S')
C
      CALL DSBGVX('V','I','U',N,KA,KB,AB,LDAB,BB,LDBB,Q,LDQ,0.D0,1.D0,
     &IL,IU,ABSTOL,M,W,Z,LDZ,WORK,IWORK,IFAIL,INFO)
C
      END SUBROUTINE DSBGVX_C
C
CCC DSBEVX
      SUBROUTINE DSBEVX_C(N,KD,AB,LDAB,M,W,WORK,IWORK,IFAIL,INFO)
     &BIND(C,NAME="dsbevx_c")
      USE :: ISO_C_BINDING
C
      IMPLICIT NONE
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: N
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: KD
      REAL(KIND=C_DOUBLE),INTENT(INOUT) :: AB
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: LDAB
      DOUBLE PRECISION :: Q
      INTEGER :: LDQ
      DOUBLE PRECISION :: ABSTOL
      INTEGER(KIND=C_INT32_T),INTENT(OUT) :: M
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: W
      DOUBLE PRECISION :: Z
      INTEGER :: LDZ
      REAL(KIND=C_DOUBLE) :: WORK
      INTEGER(KIND=C_INT32_T) :: IWORK
      INTEGER(KIND=C_INT32_T),INTENT(OUT) :: IFAIL
      INTEGER(KIND=C_INT32_T),INTENT(OUT) :: INFO
      DOUBLE PRECISION :: DLAMCH
C
      DIMENSION AB(LDAB,N),Q(1,1),W(N),Z(1,1),WORK(7*N),IWORK(5*N),
     &IFAIL(N)
C
      ABSTOL = 2.D0*DLAMCH('S')
      LDQ = 1
      LDZ = 1
C
      CALL DSBEVX('N','A','U',N,KD,AB,LDAB,Q,LDQ,0.D0,1.D0,1,1,ABSTOL,M,
     &W,Z,LDZ,WORK,IWORK,IFAIL,INFO)
C
      END SUBROUTINE DSBEVX_C
