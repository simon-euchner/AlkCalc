      SUBROUTINE DSBMV_C(N,K,ALPHA,A,LDA,X,BETA,Y)
     &BIND(C,NAME="dsbmv_c")
      USE :: ISO_C_BINDING
C
      IMPLICIT NONE
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: N
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: K
      REAL(KIND=C_DOUBLE),INTENT(IN) :: ALPHA
      REAL(KIND=C_DOUBLE),INTENT(IN) :: A
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: LDA
      REAL(KIND=C_DOUBLE),INTENT(IN) :: X
      REAL(KIND=C_DOUBLE),INTENT(IN) :: BETA
      REAL(KIND=C_DOUBLE),INTENT(INOUT) :: Y
C
      DIMENSION A(LDA,N),X(N),Y(N)
C
      CALL DSBMV('U',N,K,ALPHA,A,LDA,X,1,BETA,Y,1)
C
      END SUBROUTINE DSBMV_C
