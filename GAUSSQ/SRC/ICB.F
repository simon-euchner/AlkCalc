      SUBROUTINE GAUSSQ_C(N,T,W)
     &BIND(C,NAME="gaussq_c")
      USE :: ISO_C_BINDING
C
      IMPLICIT NONE
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: N
      REAL(KIND=C_DOUBLE) :: ENDPTS
      REAL(KIND=C_DOUBLE) :: B
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: T
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: W
C
      DIMENSION ENDPTS(2),B(N),T(N),W(N)
C
      ENDPTS(1)=0.D0
      ENDPTS(2)=0.D0
C
C     FIX SOME ARGUMENTS TO SELECT GAUSSIAN-LEGENDRE QUADRATURE
      CALL GAUSSQ(1,N,0.D0,0.D0,0,ENDPTS,B,T,W)
C
      END SUBROUTINE GAUSSQ_C
