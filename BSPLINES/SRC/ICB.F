      SUBROUTINE DBSPVD_C(T,K,NDERIV,X,ILEFT,VNIKX,WORK)
     &BIND(C,NAME="dbspvd_c")
      USE :: ISO_C_BINDING
C
      IMPLICIT NONE
      REAL(KIND=C_DOUBLE),INTENT(IN) :: T
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: K
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: NDERIV
      REAL(KIND=C_DOUBLE),INTENT(IN) :: X
      INTEGER(KIND=C_INT32_T),INTENT(IN) :: ILEFT
      REAL(KIND=C_DOUBLE),INTENT(OUT) :: VNIKX
      REAL(KIND=C_DOUBLE) :: WORK
C
      DIMENSION T(*),VNIKX(K,NDERIV),WORK((K+1)*(K+2)/2)
C
      CALL DBSPVD(T,K,NDERIV,X,ILEFT,K,VNIKX,WORK)
C
      END SUBROUTINE DBSPVD_C

